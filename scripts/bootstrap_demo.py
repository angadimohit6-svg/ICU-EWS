"""Build the synthetic demonstration bundle and train the ICU-EWS models.

Usage:
    python3 scripts/bootstrap_demo.py [--seed 7] [--patients 420] [--slug demo-cohort-v1]
"""

from __future__ import annotations

import argparse
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from icu_ews.data.demo import GENERATOR_VERSION, CohortSpec, generate_cohort
from icu_ews.data.schema import validate_bundle
from icu_ews.ml import artifacts
from icu_ews.ml.training import bundle_json, train_bundle


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--patients", type=int, default=420)
    ap.add_argument("--slug", default="demo-cohort-v1")
    args = ap.parse_args()

    started = time.time()
    print(f"[1/4] Generating synthetic cohort (n={args.patients}, seed={args.seed}) ...")
    frames = generate_cohort(CohortSpec(n_patients=args.patients, seed=args.seed))

    print("[2/4] Validating schema ...")
    problems = validate_bundle(frames["patients"], frames["observations"], frames["labs"])
    if problems:
        for problem in problems:
            print("  -", problem)
        raise SystemExit("Dataset failed validation.")

    patients = frames["patients"]
    meta = {
        "slug": args.slug,
        "label": "ICU-EWS Demo Cohort",
        "short_label": "Demo cohort (synthetic)",
        "is_demo": True,
        "description": (
            "Synthetic ICU cohort generated by ICU-EWS for product demonstration. "
            "No real patient data is included."
        ),
        "generator": GENERATOR_VERSION,
        "seed": args.seed,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "n_patients": int(len(patients)),
        "n_observations": int(len(frames["observations"])),
        "n_labs": int(len(frames["labs"])),
        "positive_rate": round(float(patients["deterioration_24h"].mean()), 4),
        "target_definition": "Documented deterioration event within 24h of the assessment window",
    }

    print("[3/4] Training models (XGBoost / Random Forest / Logistic Regression) ...")
    bundle = train_bundle(frames["patients"], frames["observations"], frames["labs"], meta)

    print("[4/4] Persisting bundle ...")
    path = artifacts.save_bundle(args.slug, frames, meta, bundle)
    sidecar = bundle_json(meta, bundle["training"])
    (path / "meta.json").write_text(__import__("json").dumps(sidecar, indent=2, default=str))

    metrics = bundle["metrics"]
    print("\nHeld-out test performance (computed, not stored constants):")
    for name, m in metrics.items():
        print(
            f"  {name:<20} AUC {m['roc_auc']:.3f} | PR-AUC {m['pr_auc']:.3f} | "
            f"F1 {m['f1']:.3f} @ thr {m['threshold']:.2f} | Brier {m['brier']:.3f}"
        )
    print(
        f"\nSplit: {bundle['training']['n_train']} train / {bundle['training']['n_test']} test | "
        f"positive rate {bundle['training']['positive_rate_train']:.1%} / "
        f"{bundle['training']['positive_rate_test']:.1%}"
    )
    print(f"Risk trajectory rows: {len(bundle['risk_table'])}")
    print(f"Saved to {path} in {time.time() - started:.1f}s")


if __name__ == "__main__":
    main()
